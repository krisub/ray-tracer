/**
 * @file ray.h
 * @brief this has the ray and intersection classes for the ray tracing engine
 *
 * the main data structures used for scenes are:
 * - `ray`: the geometric ray that is cast (origin, direction, type)
 * - `isect`: the intersection data (hit point, normal, material)
 *
 * these classes are referenced by `RayTracer`, `Scene`, `Geometry`, `Material`,
 * and others
 */

//
// ray.h
//
// The low-level classes used by ray tracing: the ray and isect classes.
//

#ifndef __RAY_H__
#define __RAY_H__

// who the hell cares if my identifiers are longer than 255 characters:
#pragma warning(disable : 4786)

#include "material.h"
#include <glm/vec2.hpp>
#include <glm/vec3.hpp>
#include <memory>

class SceneObject;
class isect;

/**
 * @brief ray_thread_id: a thread local variable for statistical purpose.
 *
 * maintains a count of rays generated by the current thread. Used by `TraceUI`
 * to display perf stats
 *
 * declared extern to be accessible by RayTracer, defined in ray.cpp
 */
extern thread_local unsigned int ray_thread_id;

// A ray has a position where the ray starts, and a direction (which should
// always be normalized!)

/**
 * @class ray
 * @brief a ray in 3D space, defined by an origin and direction
 *
 * a ray has the equation: P(t) = o + t * d. In class we refer to d as v.
 * extra metadata includes ray type (shadow v visibility) and current
 * attenuation color.
 *
 * important references:
 * - `RayTracer::traceRay`: main recursive loop
 * - `Scene::intersect`: passed to objects to test for hits
 * - `Material::shade`: to get view direction and reflection/refraction rays
 */
class ray {
public:
  /**
   * @enum RayType
   * @brief types of rays lol.
   *
   * VISIBILITY: primary or secondary ray for visible surface color
   * REFLECTION: reflection ray
   * REFRACTION: refraction ray
   * SHADOW: shadow ray
   */
  enum RayType { VISIBILITY, REFLECTION, REFRACTION, SHADOW };

  /**
   * @brief ray contructor
   *
   * initializes ray and increments global ray counter via `TraceUI`
   *
   * @param pp origin point
   * @param dd direction vector (should be normalized)
   * @param w attenuation color. stops recursion if ray does not contribute to
   * final image.
   * @param tt ray type (default VISIBILITY)
   */
  ray(const glm::dvec3 &pp, const glm::dvec3 &dd, const glm::dvec3 &w,
      RayType tt = VISIBILITY);

  /**
   * @brief copy constructor
   *
   * copies all properties and increments global ray counter
   *
   * @param other ray to copy
   */
  ray(const ray &other);

  /**
   * @brief destructor
   */
  ~ray();

  /**
   * @brief assignment
   * @param other the ray to assign from
   * @return reference to this ray
   */
  ray &operator=(const ray &other);

  /**
   * @brief at: compute point along ray at distance t
   *
   * formula: P(t) = o + t * d
   *
   * @param t distance along ray ("time of flight")
   * @return glm::dvec3: 3D coords of point
   */
  glm::dvec3 at(double t) const { return p + (t * d); }

  /**
   * @brief at: compute point along ray at intersection
   *
   * wrapper for at(i.getT())
   *
   * @param i the intersection point with the distance t
   * @return glm::dvec3: 3D coords of point
   */
  glm::dvec3 at(const isect &i) const;

  /** @return the origin of the ray */
  glm::dvec3 getPosition() const { return p; }
  /** @return the direction of the ray */
  glm::dvec3 getDirection() const { return d; }
  /** @return the current attenuation of the ray */
  glm::dvec3 getAtten() const { return atten; }
  /** @return the type of the ray */
  RayType type() const { return t; }
  /**
   * @brief update ray's origin
   * @param pp new origin point
   */
  void setPosition(const glm::dvec3 &pp) { p = pp; }
  /**
   * @brief update ray's direction
   * @param dd new direction vector
   */
  void setDirection(const glm::dvec3 &dd) { d = dd; }

private:
  glm::dvec3 p;     ///< origin
  glm::dvec3 d;     ///< direction (normalized)
  glm::dvec3 atten; ///< attenuation vector (recursive weight)
  RayType t;        ///< ray type
};

// The description of an intersection point.

/**
 * @class isect
 * @brief data about a ray-object intersection
 *
 * when `Scene::intersect` finds an intersection between a ray and an object,
 * this object is populated with the closest hit information.
 *
 * an intersection contains:
 * - the object that was hit
 * - the distance t along the ray
 * - the surface normal at the intersection point
 * - the uv coordinates at the intersection point
 * - the barycentric coordinates at the intersection point (for interpolating
 *   vertex data)
 * - an optional material (if the intersection has its own material from
 *   interpolation, rather than using the object's material)
 *
 * important references:
 * - `Scene::intersect`: fills in this data structure.
 * - `RayTracer::traceRay`: uses this data to calculate shading.
 * - `Material::shade`: uses this data to compute shading.
 */
class isect {
public:
  /**
   * @brief isect constructor
   * initializes t to 0.0, obj to NULL, material to nullptr
   */
  isect()
      : obj(NULL), t(0.0), N(), uvCoordinates(), bary(), material(nullptr) {}

  /**
   * @brief copy constructor
   * @param other the intersection to copy from
   */
  isect(const isect &other) { copyFromOther(other); }

  /**
   * @brief destructor
   */
  ~isect() {}

  /**
   * @brief assignment operator
   * @param other the intersection to assign from
   * @return reference to this intersection
   */
  isect &operator=(const isect &other) {
    copyFromOther(other);
    return *this;
  }

  /**
   * @brief sets the geometric object that was hit
   * @param o ptr to the SceneObject (Sphere, Box, TrimeshFace)
   */
  void setObject(const SceneObject *o) { obj = o; }

  /**
   * @brief set the distance along the ray to the intersection
   * @param tt the t value
   */
  void setT(double tt) { t = tt; }
  /** @return the distance along the ray to the intersection */
  double getT() const { return t; }
  // Get/Set surface normal at this intersection.
  /**
   * @brief set the surface normal at the intersection
   * @param n the normal vector (should be normalized)
   */
  void setN(const glm::dvec3 &n) { N = n; }
  /** @return the surface normal at the intersection */
  glm::dvec3 getN() const { return N; }

  /**
   * @brief set the material at this intersection
   *
   * used when material properties are interpolated (across a triangle face)
   * and distinct from the base object's material.
   *
   * @param m the material to set
   */
  void setMaterial(const Material &m) {
    if (material)
      *material = m;
    else
      material.reset(new Material(m));
  }
  /**
   * @brief set the uv texture coordinates at this intersection
   * @param coords the uv coordinates (2D, [0..1])
   */
  void setUVCoordinates(const glm::dvec2 &coords) { uvCoordinates = coords; }
  /** @return glm::dvec2: the uv texture coordinates at this intersection */
  glm::dvec2 getUVCoordinates() const { return uvCoordinates; }
  /**
   * @brief sets the barycentric coordinates of the hit (for triangles).
   * @param weights the barycentric weights (u, v, w) or (alpha, beta, gamma).
   */
  void setBary(const glm::dvec3 &weights) { bary = weights; }
  /**
   * @brief sets the barycentric coordinates of the hit (for triangles).
   * @param alpha the first barycentric weight
   * @param beta the second barycentric weight
   * @param gamma the third barycentric weight
   */
  void setBary(const double alpha, const double beta, const double gamma) {
    setBary(glm::dvec3(alpha, beta, gamma));
  }
  /**
   * @brief retrieves the effective material at the intersection
   *
   * if a specific material was set via `setMaterial`, it returns that.
   * otherwise, it returns the material of the `obj` that was hit.
   *
   * @return reference to the material.
   */
  const Material &getMaterial() const;

private:
  /**
   * @brief internal helper to deep copy data from another intersection object.
   * handles unique_ptr logic for the material.
   * @param other the object to copy from
   */
  void copyFromOther(const isect &other) {
    if (this == &other)
      return;
    obj = other.obj;
    t = other.t;
    N = other.N;
    bary = other.bary;
    uvCoordinates = other.uvCoordinates;
    if (other.material) {
      setMaterial(*other.material);
    } else {
      material.reset();
    }
  }

  const SceneObject *obj;   ///< the object hit by the ray
  double t;                 ///< distance along the ray to the hit
  glm::dvec3 N;             ///< surface normal at the hit
  glm::dvec2 uvCoordinates; ///< texture coordinates (u, v)
  glm::dvec3 bary;          ///< barycentric coordinates (for meshes)

  // if this intersection has its own material (as opposed to one in its
  // associated object) as in the case where the material was interpolated
  /**
   * @brief optional material at the intersection
   * used for interpolated materials on meshes. if null, use object's material.
   */
  std::unique_ptr<Material> material;
};

/**
 * @brief epsilon value of 1e-8, used to prevent self-intersection
 * and force rays to start slightly off the surface.
 */
const double RAY_EPSILON = 0.00000001;

#endif // __RAY_H__
